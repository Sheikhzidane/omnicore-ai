#!/usr/bin/env node
// Generates types/database.ts from the migrated schema — no hand-maintained
// table types, so code and migrations cannot drift.
//
//   TEST_DATABASE_URL=postgres://… npm run db:types
//
// Builds a throwaway database from supabase/migrations (tests/db/harness.mjs),
// introspects it, writes the file, drops the database. Never point it at a
// real project. CHECK (col IN (...)) constraints become string-literal unions.
import { writeFileSync } from 'node:fs'
import { createMigratedDatabase, databaseUrl } from '../tests/db/harness.mjs'

if (!databaseUrl()) {
  console.error('TEST_DATABASE_URL is required (a disposable Postgres server).')
  process.exit(1)
}

// jsonb columns with a known shape.
const JSON_OVERRIDES = { 'todos.comments': 'TodoComment[]' }

// Hand-written RPC signatures (functions are few and security-sensitive).
const FUNCTIONS = `
      current_user_is_platform_admin: { Args: Record<string, never>; Returns: boolean }
      sync_platform_admin: { Args: { p_user_id: string; p_is_admin: boolean }; Returns: undefined }
      claim_agent_tasks: { Args: { p_limit?: number }; Returns: AgentTaskRow[] }
      claim_publishing_jobs: { Args: { p_limit?: number }; Returns: PublishingJobRow[] }
      complete_publishing_job: {
        Args: { p_job_id: string; p_success: boolean; p_external_post_id?: string | null; p_url?: string | null; p_error?: string | null; p_response?: Json }
        Returns: PublishingJobRow
      }
      reap_stuck_publishing_jobs: { Args: { p_older_than?: string }; Returns: number }
      store_social_credential: { Args: { p_social_account_id: string; p_ciphertext: string }; Returns: undefined }
      read_social_credential: { Args: { p_social_account_id: string }; Returns: string | null }
      delete_social_credential: { Args: { p_social_account_id: string }; Returns: undefined }`

const pascal = s => s.split('_').map(p => p[0].toUpperCase() + p.slice(1)).join('')

function tsType(udt, isArray) {
  const base = {
    uuid: 'string', text: 'string', varchar: 'string', citext: 'string', bpchar: 'string',
    int2: 'number', int4: 'number', int8: 'number', float4: 'number', float8: 'number', numeric: 'number',
    bool: 'boolean', jsonb: 'Json', json: 'Json',
    timestamptz: 'string', timestamp: 'string', date: 'string', time: 'string', interval: 'string',
  }[udt.replace(/^_/, '')] ?? 'unknown'
  return isArray ? `${base}[]` : base
}

const db = await createMigratedDatabase()
try {
  const c = db.client
  const rels = (await c.query(`
    select c.relname as name, c.relkind as kind from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind in ('r','v') order by c.relname`)).rows
  const cols = (await c.query(`
    select table_name, column_name, udt_name, data_type, is_nullable, column_default, ordinal_position
    from information_schema.columns where table_schema = 'public' order by table_name, ordinal_position`)).rows
  const checks = (await c.query(`
    select c.relname as table_name, pg_get_constraintdef(k.oid) as def
    from pg_constraint k join pg_class c on c.oid = k.conrelid join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and k.contype = 'c'`)).rows

  // (col = ANY (ARRAY['a'::text, 'b'::text])) → union for that column
  const unions = {}
  for (const { table_name, def } of checks) {
    const m = def.match(/^CHECK \(\(\(?(\w+)\)? = ANY \(\(?ARRAY\[(.+?)\]\)?(?:::text\[\])?\)\)\)$/)
    if (!m) continue
    const values = [...m[2].matchAll(/'([^']*)'::text/g)].map(v => v[1])
    if (values.length) unions[`${table_name}.${m[1]}`] = values.map(v => `'${v}'`).join(' | ')
  }

  const out = []
  out.push(`/**
 * Supabase Database type — GENERATED by scripts/generate-db-types.mjs from
 * supabase/migrations. Do not edit by hand: change a migration, then run
 * \`TEST_DATABASE_URL=… npm run db:types\`. tests/db/schema-types.test.mjs
 * fails if this file and the migrations disagree.
 */

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]

export type TodoComment = { agent: string; text: string; at: string }
`)
  const tableLines = [], viewLines = []
  for (const rel of rels) {
    const rc = cols.filter(x => x.table_name === rel.name)
    const rowName = `${pascal(rel.name)}Row`
    out.push(`export type ${rowName} = {`)
    const required = []
    for (const col of rc) {
      const key = `${rel.name}.${col.column_name}`
      let t = JSON_OVERRIDES[key] ?? unions[key] ?? tsType(col.udt_name, col.data_type === 'ARRAY')
      if (col.is_nullable === 'YES') t += ' | null'
      out.push(`  ${col.column_name}: ${t}`)
      if (rel.kind === 'r' && col.is_nullable === 'NO' && col.column_default === null) required.push(`'${col.column_name}'`)
    }
    out.push('}\n')
    if (rel.kind === 'r') {
      tableLines.push(`      ${rel.name}: Table<${rowName}, ${required.length ? required.join(' | ') : 'never'}>`)
    } else {
      viewLines.push(`      ${rel.name}: { Row: ${rowName}; Relationships: [] }`)
    }
  }

  out.push(`type Table<Row, Required extends keyof Row> = {
  Row: Row
  Insert: Pick<Row, Required> & Partial<Omit<Row, Required>>
  Update: Partial<Row>
  Relationships: []
}

export interface Database {
  __InternalSupabase: { PostgrestVersion: '12' }
  public: {
    Tables: {
${tableLines.join('\n')}
    }
    Views: {
${viewLines.join('\n')}
    }
    Functions: {${FUNCTIONS}
    }
    Enums: { [_ in never]: never }
    CompositeTypes: { [_ in never]: never }
  }
}

export type TableName = keyof Database['public']['Tables']
export type Tables<T extends TableName> = Database['public']['Tables'][T]['Row']
export type TablesInsert<T extends TableName> = Database['public']['Tables'][T]['Insert']
export type TablesUpdate<T extends TableName> = Database['public']['Tables'][T]['Update']

// Convenience aliases used across the app.
export type WorkspaceRole = WorkspaceMembersRow['role']
export type AgentRole = AgentsRow['role']
export type AgentRow = AgentsRow
export type CharacterRow = CharactersRow
export type TodoRow = TodosRow
export type TraceRow = TracesRow
export type PublishingJobRow = PublishingJobsRow
export type AgentTaskRow = AgentTasksRow
export type PublishingPolicyRow = PublishingPoliciesRow
/** Platforms with built-in providers (the schema accepts any registered provider id). */
export type SocialPlatform = 'instagram' | 'tiktok' | 'youtube' | 'x'
`)
  writeFileSync('types/database.ts', out.join('\n'))
  console.log(`✓ types/database.ts generated: ${tableLines.length} tables, ${viewLines.length} views`)
} finally {
  await db.drop()
}
